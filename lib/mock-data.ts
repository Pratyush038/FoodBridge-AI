// Function to seed mock data to Supabase
export async function seedMockData(supabase: any) {
  try {
    console.log('🌱 Seeding mock data for Bangalore...');

    let donorsInserted = 0;
    let ngosInserted = 0;
    let foodDonationsInserted = 0;
    let requirementsInserted = 0;
    const errors: any[] = [];

    // Insert donors one by one to get better error messages
    for (const donor of mockDonors) {
      // Only include fields that exist in the simplified schema
      const donorData: any = {
        id: donor.id,
        user_id: donor.user_id,
        name: donor.name,
        email: donor.email,
        phone: donor.phone,
        organization_name: donor.organization_name,
        address: donor.address,
        latitude: donor.latitude,
        longitude: donor.longitude,
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
      };

      const { data, error } = await supabase
        .from('donors')
        .upsert(donorData, { 
          onConflict: 'id',
          ignoreDuplicates: false 
        })
        .select();

      if (error) {
        console.error(`Error seeding donor ${donor.name}:`, error);
        errors.push({ type: 'donor', name: donor.name, error });
      } else {
        donorsInserted++;
        console.log(`✅ Seeded donor: ${donor.name}`);
      }
    }

    // Insert NGOs one by one to get better error messages
    for (const ngo of mockNGOs) {
      // Only include fields that exist in the simplified schema
      const ngoData: any = {
        id: ngo.id,
        user_id: ngo.user_id,
        name: ngo.name,
        email: ngo.email,
        phone: ngo.phone,
        address: ngo.address,
        latitude: ngo.latitude,
        longitude: ngo.longitude,
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
      };

      const { data, error } = await supabase
        .from('ngos')
        .upsert(ngoData, { 
          onConflict: 'id',
          ignoreDuplicates: false 
        })
        .select();

      if (error) {
        console.error(`Error seeding NGO ${ngo.name}:`, error);
        errors.push({ type: 'ngo', name: ngo.name, error });
      } else {
        ngosInserted++;
        console.log(`✅ Seeded NGO: ${ngo.name}`);
      }
    }

    // Insert food donations
    for (const donation of mockFoodDonations) {
      const donationData = {
        ...donation,
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
      };

      const { data, error } = await supabase
        .from('food_items')
        .insert(donationData)
        .select();

      if (error) {
        console.error(`Error seeding food donation:`, error);
        errors.push({ type: 'food_donation', error });
      } else {
        foodDonationsInserted++;
        console.log(`✅ Seeded food donation: ${donation.food_type}`);
      }
    }

    // Insert food requirements
    for (const requirement of mockFoodRequirements) {
      const requirementData = {
        ...requirement,
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
      };

      const { data, error } = await supabase
        .from('requests')
        .insert(requirementData)
        .select();

      if (error) {
        console.error(`Error seeding requirement:`, error);
        errors.push({ type: 'requirement', error });
      } else {
        requirementsInserted++;
        console.log(`✅ Seeded requirement: ${requirement.title}`);
      }
    }

    console.log(`🎉 Mock data seeding completed!`);
    console.log(`   Donors: ${donorsInserted}/${mockDonors.length}`);
    console.log(`   NGOs: ${ngosInserted}/${mockNGOs.length}`);
    console.log(`   Food Donations: ${foodDonationsInserted}/${mockFoodDonations.length}`);
    console.log(`   Requirements: ${requirementsInserted}/${mockFoodRequirements.length}`);
    
    if (errors.length > 0) {
      console.error('❌ Some entries failed:', errors);
      return { 
        success: false, 
        donorsCount: donorsInserted, 
        ngosCount: ngosInserted,
        foodDonationsCount: foodDonationsInserted,
        requirementsCount: requirementsInserted,
        error: `Failed to insert ${errors.length} entries. Check server logs.`,
        errors 
      };
    }
    
    return { 
      success: true, 
      donorsCount: donorsInserted, 
      ngosCount: ngosInserted,
      foodDonationsCount: foodDonationsInserted,
      requirementsCount: requirementsInserted,
    };
  } catch (error) {
    console.error('Error in seedMockData:', error);
    return { 
      success: false, 
      error, 
      donorsCount: 0, 
      ngosCount: 0,
      foodDonationsCount: 0,
      requirementsCount: 0,
    };
  }
}

