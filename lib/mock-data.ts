// Helper functions for relative dates
const getRelativeDate = (daysOffset: number, hoursOffset: number = 0): string => {
  const now = new Date();
  const targetDate = new Date(now.getTime() + daysOffset * 24 * 60 * 60 * 1000 + hoursOffset * 60 * 60 * 1000);
  return targetDate.toISOString();
};

// Convenience functions for common relative dates
const today = (hoursOffset: number = 0) => getRelativeDate(0, hoursOffset);
const yesterday = (hoursOffset: number = 0) => getRelativeDate(-1, hoursOffset);
const daysAgo = (days: number, hoursOffset: number = 0) => getRelativeDate(-days, hoursOffset);
const daysFromNow = (days: number, hoursOffset: number = 0) => getRelativeDate(days, hoursOffset);

